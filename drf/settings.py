def _check_db_reachable(host, port):
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.settimeout(0.3)
            return s.connect_ex((host, int(port))) == 0
    except Exception:
        return False

_db_engine = config('DB_ENGINE', default='django.db.backends.mysql')
